CREATE TABLE games (
  id text PRIMARY KEY,
  game_type text NOT NULL DEFAULT 'werewolf',
  mode text NOT NULL,
  skin_id text REFERENCES skins(id) ON DELETE SET NULL,
  skin_name text NOT NULL DEFAULT '',
  winner text,
  win_reason text NOT NULL DEFAULT '',
  topic_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  players_json jsonb NOT NULL,
  rounds_json jsonb NOT NULL,
  event_json jsonb NOT NULL,
  audio_resources_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_games_type_created ON games(game_type, created_at DESC);

CREATE TABLE game_players (
  game_id text NOT NULL REFERENCES games(id) ON DELETE CASCADE,
  player_id bigint NOT NULL REFERENCES players(id) ON DELETE RESTRICT,
  player_snapshot_json jsonb NOT NULL,
  PRIMARY KEY (game_id, player_id)
);

CREATE TABLE game_playback_events (
  game_id text NOT NULL REFERENCES games(id) ON DELETE CASCADE,
  sequence integer NOT NULL,
  protocol_version integer NOT NULL,
  event_type text NOT NULL,
  view_mode text NOT NULL,
  payload_json jsonb NOT NULL,
  media_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (game_id, sequence)
);
CREATE INDEX idx_game_playback_events_game ON game_playback_events(game_id, sequence);

CREATE TABLE game_player_selections (
  game_type text PRIMARY KEY,
  player_ids_json jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE player_game_memories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_type text NOT NULL,
  owner_player_id bigint NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  subject_player_id bigint NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  games_played integer NOT NULL DEFAULT 0,
  familiarity_score double precision NOT NULL DEFAULT 0,
  traits_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  recent_summary text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(game_type, owner_player_id, subject_player_id)
);
CREATE INDEX idx_player_game_memories_lookup
  ON player_game_memories(game_type, owner_player_id, games_played DESC, familiarity_score DESC);

CREATE TABLE matches (
  id text PRIMARY KEY,
  game_type text NOT NULL,
  workflow_id text NOT NULL,
  status text NOT NULL DEFAULT 'running',
  current_step_index integer NOT NULL DEFAULT 0,
  version integer NOT NULL DEFAULT 0,
  config_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  state_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  blockers_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  error_json jsonb NOT NULL DEFAULT 'null'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
);

CREATE TABLE match_snapshots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id text NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
  version integer NOT NULL,
  status text NOT NULL,
  current_step_index integer NOT NULL,
  last_event_seq integer,
  state_json jsonb NOT NULL,
  blockers_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_match_snapshots_match ON match_snapshots(match_id, version DESC);

CREATE TABLE workflow_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id text NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
  seq integer NOT NULL,
  type text NOT NULL,
  step_id text,
  player_id text,
  payload_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  visibility text NOT NULL DEFAULT 'public',
  visible_to_player_ids_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  idempotency_key text,
  channel text NOT NULL DEFAULT 'public',
  scope_key text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(match_id, seq),
  UNIQUE(match_id, idempotency_key)
);
CREATE INDEX idx_workflow_events_match_seq ON workflow_events(match_id, seq);
CREATE INDEX idx_workflow_events_type ON workflow_events(type);
CREATE INDEX idx_workflow_events_channel ON workflow_events(match_id, channel);
CREATE INDEX idx_workflow_events_scope ON workflow_events(match_id, channel, scope_key);

