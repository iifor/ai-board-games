CREATE TABLE game_traces (
  id text PRIMARY KEY,
  game_type text NOT NULL,
  game_mode text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'recording',
  llm_call_count integer NOT NULL DEFAULT 0,
  agent_decision_count integer NOT NULL DEFAULT 0,
  event_count integer NOT NULL DEFAULT 0,
  error_message text,
  participants_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL,
  completed_at timestamptz,
  duration_ms integer
);

CREATE TABLE trace_spans (
  id text PRIMARY KEY,
  trace_id text NOT NULL REFERENCES game_traces(id) ON DELETE CASCADE,
  parent_span_id text,
  span_type text NOT NULL,
  span_name text NOT NULL,
  start_time timestamptz NOT NULL,
  end_time timestamptz,
  status text NOT NULL DEFAULT 'ok',
  attributes_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  error_json jsonb,
  created_at timestamptz NOT NULL
);
CREATE INDEX idx_spans_trace ON trace_spans(trace_id);
CREATE INDEX idx_spans_parent ON trace_spans(parent_span_id);

