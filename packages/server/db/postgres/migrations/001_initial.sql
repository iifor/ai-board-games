CREATE TABLE skins (
  id text PRIMARY KEY,
  name text NOT NULL,
  version text NOT NULL DEFAULT 'v3.2',
  source text NOT NULL DEFAULT 'admin',
  terms_json jsonb NOT NULL,
  background text NOT NULL,
  truth text NOT NULL DEFAULT '',
  clues_json jsonb NOT NULL,
  noises_json jsonb NOT NULL,
  memory_examples_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  enabled integer NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE model_providers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  base_url text NOT NULL DEFAULT '',
  api_format text NOT NULL DEFAULT 'openai-compatible',
  api_key_cipher text NOT NULL DEFAULT '',
  api_key_iv text NOT NULL DEFAULT '',
  api_key_tag text NOT NULL DEFAULT '',
  enabled integer NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE models (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id bigint REFERENCES model_providers(id) ON DELETE RESTRICT,
  provider text NOT NULL,
  name text NOT NULL,
  display_name text NOT NULL DEFAULT '',
  base_url text NOT NULL DEFAULT '',
  api_format text NOT NULL DEFAULT 'openai-compatible',
  api_key_cipher text NOT NULL DEFAULT '',
  api_key_iv text NOT NULL DEFAULT '',
  api_key_tag text NOT NULL DEFAULT '',
  enabled integer NOT NULL DEFAULT 1,
  thinking_enabled integer NOT NULL DEFAULT 0,
  disabled_reason text,
  disabled_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

