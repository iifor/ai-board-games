export function describeRules(roles: Readonly<Record<string, number | 'rest'>>, config: BoardConfig): string {
  const roleLines = Object.keys(roles).flatMap((role) => {
    const rule = ROLE_RULES[role];
    if (rule === undefined) return [];
    return [typeof rule === 'string' ? rule : rule(config)];
  });
  return [...BASE_RULES, ...roleLines].join('\n');
}
