import { speechOutput } from '@battle/engine';
import { werewolfPrompts as prompts } from '../prompts';
import {
  aliveWolves,
  applyWitchPoison,
  applyWitchSave,
  describeSeerCheck,
  recordSeerCheck,
  recordWolfKill,
  resetNight,
  resolveNight,
  witchPoisonTargets,
  witchSaveTargets,
  wolfChatOrder,
  wolfKillTargets,
} from '../rules/night';
